// Generates src/content/travel/world-path.ts — the landmass silhouette for the
// travel route chart — from Natural Earth 110m land polygons (public domain).
//
// Usage:
//   node scripts/travel-world-path.mjs             # fetch data from GitHub
//   node scripts/travel-world-path.mjs --from f.geojson  # use a local file
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCE_URL =
  'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson';

// Must match the projection in TravelPage.tsx; PROJ_SCALE is re-exported from
// the generated file so the two cannot drift.
const PROJ_SCALE = 3;
const project = ([lon, lat]) => [
  Math.round((lon + 180) * PROJ_SCALE * 10) / 10,
  Math.round((90 - lat) * PROJ_SCALE * 10) / 10,
];

const fromIndex = process.argv.indexOf('--from');
let raw;
if (fromIndex !== -1) {
  raw = await readFile(process.argv[fromIndex + 1], 'utf8');
} else {
  const res = await fetch(SOURCE_URL);
  if (!res.ok) throw new Error(`Fetch failed: ${res.status} ${res.statusText}`);
  raw = await res.text();
}

const geojson = JSON.parse(raw);

const ringToPath = (ring) => {
  const pts = ring.map(project);
  const segments = [`M${pts[0][0]} ${pts[0][1]}`];
  for (let i = 1; i < pts.length; i++) {
    const [x, y] = pts[i];
    const [px, py] = pts[i - 1];
    if (x === px && y === py) continue; // drop points collapsed by rounding
    segments.push(`L${x} ${y}`);
  }
  segments.push('Z');
  return segments.join('');
};

const paths = [];
for (const feature of geojson.features) {
  const { type, coordinates } = feature.geometry;
  const polygons = type === 'Polygon' ? [coordinates] : coordinates;
  for (const polygon of polygons) {
    for (const ring of polygon) {
      paths.push(ringToPath(ring));
    }
  }
}

const outFile = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  '../src/content/travel/world-path.ts'
);
const banner = `// Generated by scripts/travel-world-path.mjs — do not edit by hand.
// Landmass silhouette from Natural Earth 110m land polygons (public domain),
// projected equirectangularly onto a ${360 * PROJ_SCALE}×${180 * PROJ_SCALE} plane.
`;
await writeFile(
  outFile,
  `${banner}export const PROJ_SCALE = ${PROJ_SCALE};\n\nexport const WORLD_PATH =\n  '${paths.join('')}';\n`
);
console.log(`Wrote ${outFile} (${paths.length} rings)`);
